#!/bin/sh
# Writes THIRD_PARTY_NOTICES.md: the license of every module compiled into the veilox binary.
# Run after changing dependencies: ./scripts/third-party-notices.sh
set -eu
cd "$(dirname "$0")/.."
out=THIRD_PARTY_NOTICES.md
{
  echo "# Third-party notices"
  echo
  echo "The veilox binary includes the following modules. Their licenses are reproduced below."
  echo "Generated by \`scripts/third-party-notices.sh\`."
  go list -deps -f '{{if not .Standard}}{{with .Module}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' ./cmd/veilox |
    sort -u | grep -v '^github.com/jsxd3v/veilox ' |
    while read -r path version dir; do
      license=$(ls "$dir" | grep -iE '^(LICENSE|LICENCE|COPYING)(\.(md|txt))?$' | head -1)
      echo
      echo "## $path $version"
      echo
      echo '```text'
      cat "$dir/$license"
      echo '```'
    done
} > "$out"
echo "wrote $out"
